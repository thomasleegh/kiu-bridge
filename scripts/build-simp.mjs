// Builds the Traditional → Simplified table that index.html uses to show Mandarin in Simplified
// characters (Cantonese stays Traditional). Run after rebuilding dict.json: node scripts/build-simp.mjs
// It rewrites the block between "// <simp-map>" and "// </simp-map>" in index.html.
//   - per character: the Simplified form CC-CEDICT gives most often (weighted by Mandarin frequency)
//   - per word: common words where character-by-character gets it wrong (著名 stays 著名, 反覆 → 反复)
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.join(path.dirname(new URL(import.meta.url).pathname), '..');
const dict = JSON.parse(fs.readFileSync(path.join(ROOT, 'dict.json'), 'utf8'));

const votes = new Map();
for(const r of dict.rows){
  const t = [...r[0]], s = [...(r[1] || r[0])];
  if(t.length !== s.length) continue;
  const w = 1 + r[5] + (t.length === 1 ? 5 : 0);
  t.forEach((c, i) => {
    if(!votes.has(c)) votes.set(c, new Map());
    const m = votes.get(c); m.set(s[i], (m.get(s[i]) || 0) + w);
  });
}
const chars = new Map();
for(const [t, m] of votes){
  const best = [...m].sort((a, b) => b[1] - a[1])[0][0];
  if(best !== t) chars.set(t, best);
}
// A character that is itself a Simplified result must never be converted again (么 → 幺),
// so text that is already Simplified comes through unchanged.
const outputs = new Set(chars.values());
for(const k of [...chars.keys()]) if(outputs.has(k)) chars.delete(k);

const conv = (x) => [...x].map(c => chars.get(c) || c).join('');
const words = [];
for(const r of dict.rows){
  const simp = r[1] || r[0];
  if([...r[0]].length > 1 && r[5] >= 5 && conv(r[0]) !== simp) words.push(r[0] + ':' + simp);
}

const block = `// <simp-map> — generated by scripts/build-simp.mjs from dict.json; don't edit by hand.
const SIMP_CHARS = ${JSON.stringify([...chars].map(([t, s]) => t + s).join(''))};
const SIMP_WORDS = ${JSON.stringify(words.join(','))};
// </simp-map>`;
const htmlPath = path.join(ROOT, 'index.html');
const html = fs.readFileSync(htmlPath, 'utf8');
const a = html.indexOf('// <simp-map>'), b = html.indexOf('// </simp-map>');
if(a < 0 || b < 0){ console.error('simp-map markers not found in index.html'); process.exit(1); }
fs.writeFileSync(htmlPath, html.slice(0, a) + block + html.slice(b + '// </simp-map>'.length));
console.log(`simp-map: ${chars.size} characters, ${words.length} word exceptions`);
